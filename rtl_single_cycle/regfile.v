// ============================================================================
// regfile.v —— 通用寄存器堆（32 × 32，2 读 1 写，带同拍旁路）
// ----------------------------------------------------------------------------
// 规则（LA32R 手册）：
//   - r0 恒为 0，写 r0 被忽略
//   - 读口为异步读（组合逻辑），写口为时钟上升沿写入
//   - 同拍旁路（结构冒险之一）：同一拍「写地址 == 读地址」时，读口直接
//     输出写数据（写穿透），否则本拍读出的仍是旧值
// 这是单周期版的关键结构冒险点，答辩要能指出：寄存器堆同一拍又读又写，
// 单端口存储无法同拍完成，靠内部旁路解决。
// ============================================================================
module regfile (
    input  wire        clk,     // 时钟
    input  wire        we,      // 写使能
    input  wire [4:0]  ra1,     // 读地址 1（源操作数 A）
    input  wire [4:0]  ra2,     // 读地址 2（源操作数 B / 分支比较）
    input  wire [4:0]  wa,      // 写地址（目的寄存器）
    input  wire [31:0] wd,      // 写数据
    output wire [31:0] rd1,     // 读数据 1
    output wire [31:0] rd2      // 读数据 2
);

    reg [31:0] regs [0:31];
    integer i;
    // 上电清零（分布式 RAM 初始化）
    initial for (i = 0; i < 32; i = i + 1) regs[i] = 32'd0;

    // 异步读 + 写穿透旁路（排除 r0：wa==0 时禁止旁路，保证 r0 恒 0）
    assign rd1 = (we && (wa != 5'd0) && (wa == ra1)) ? wd : regs[ra1];
    assign rd2 = (we && (wa != 5'd0) && (wa == ra2)) ? wd : regs[ra2];

    // 同步写（r0 恒 0，不写入）
    always @(posedge clk) begin
        if (we && (wa != 5'd0))
            regs[wa] <= wd;
    end

endmodule
