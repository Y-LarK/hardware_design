// ============================================================================
// regfile.v —— 通用寄存器堆（32 × 32，2 读 1 写，异步读）
// ----------------------------------------------------------------------------
// 规则（LA32R 手册）：
//   - r0 恒为 0，写 r0 被忽略
//   - 读口为异步读（组合逻辑），写口为时钟上升沿写入
//   - 单周期 CPU 写回在时钟沿完成，上一拍结果在沿后已可读，
//     因此读口直接读寄存器，不需要写穿透旁路。
// ============================================================================
module regfile (
    input  wire        clk,     // 时钟
    input  wire        we,      // 写使能
    input  wire [4:0]  ra1,     // 读地址 1（源操作数 A）
    input  wire [4:0]  ra2,     // 读地址 2（源操作数 B / 分支比较）
    input  wire [4:0]  wa,      // 写地址（目的寄存器）
    input  wire [31:0] wd,      // 写数据
    output wire [31:0] rd1,     // 读数据 1
    output wire [31:0] rd2      // 读数据 2
);

    reg [31:0] regs [0:31];
    integer i;
    // 上电清零（分布式 RAM 初始化）
    initial for (i = 0; i < 32; i = i + 1) regs[i] = 32'd0;

    // 异步读（单周期：写回在时钟沿完成，上一拍结果沿后已可读，不需要旁路；
    // 若本拍读=写同寄存器时输出 wd 会形成组合环，故取消写穿透）
    assign rd1 = regs[ra1];
    assign rd2 = regs[ra2];

    // 同步写（r0 恒 0，不写入）
    always @(posedge clk) begin
        if (we && (wa != 5'd0))
            regs[wa] <= wd;
    end

endmodule
