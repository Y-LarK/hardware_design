// ============================================================================
// imem.v —— 指令存储器（单周期版：分布式 RAM，异步读）
// ----------------------------------------------------------------------------
// 容量：4 KB = 1024 条 × 32 位（本项目只用 1/4）
// 实现要点（DESIGN.md §3.5）：
//   单周期 CPU 要求「同拍取指、执行、写回」，Block RAM 的同步读（本拍送
//   地址、下拍出数据）无法满足，因此必须用 LUT 实现的分布式 RAM（异步读，
//   组合逻辑直接出指令）。这是 FPGA 上单周期版与流水线版存储器的关键差异。
// 地址映射（方案 A）：复位 PC=0x1C000000，IMEM 从 0 地址开始，
//   取指地址 = pc[11:2]（忽略高 20 位），把 0x1C000000 起的空间映射到 RAM 的 0 地址。
// ============================================================================
module imem (
    input  wire [9:0]  addr,    // 取指地址：pc[11:2]
    output wire [31:0] instr    // 读出的 32 位指令
);

    // 1024 × 32 分布式 RAM
    reg [31:0] mem [0:1023];

    // 程序初始化：$readmemh 把十六进制机器码文件装入 IMEM
    // 文件默认放在工程根目录（综合/仿真时把 .mem/.hex 放在运行目录即可）
    `ifndef IMEM_FILE
    `define IMEM_FILE "test_all.hex"
    `endif
    initial $readmemh(`IMEM_FILE, mem);

    // 异步读：组合逻辑直接输出（单周期要求）
    assign instr = mem[addr];

endmodule
