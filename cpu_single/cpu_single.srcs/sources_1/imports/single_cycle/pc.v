// ============================================================================
// pc.v —— 程序计数器（单周期）
// ----------------------------------------------------------------------------
// 功能：每个时钟上升沿把 next_pc 打入 PC 寄存器。
//   - 复位值 0x1C000000（LA32R 手册规定复位入口地址）
//   - 单周期版每拍必取指，en 恒为 1（保留接口，便于以后改流水线时冻结 PC）
//   - 下一 PC 由 cpu_top 中的组合逻辑计算（顺序 +4 / 分支 / 跳转）
// ============================================================================
module pc (
    input  wire        clk,      // 时钟
    input  wire        rst_n,    // 复位（低有效，同步复位）
    input  wire        en,       // 使能：1=PC 更新（单周期恒 1）
    input  wire [31:0] next_pc,  // 下一 PC
    output reg  [31:0] pc        // 当前 PC
);

    // LA32R 复位入口：0x1C000000
    localparam RST_PC = 32'h1C000000;

    always @(posedge clk) begin
        if (!rst_n)
            pc <= RST_PC;
        else if (en)
            pc <= next_pc;
    end

endmodule
