// 来源：archive/single_cycle/rtl/regfile.v（流水线 Step 1 复用）
// 改动：增加同拍写穿透（WB 写口地址 == ID 读口地址时直接输出写数据）。
// ----------------------------------------------------------------------------
// regfile.v —— 通用寄存器堆（32 × 32，2 读 1 写，异步读 + 同拍写穿透）
// ----------------------------------------------------------------------------
// 规则（LA32R 手册）：
//   - r0 恒为 0，写 r0 被忽略
//   - 读口为异步读（组合逻辑），写口为时钟上升沿写入
//   - 流水线版 WB 写回与 ID 读口可能在同一拍访问同一寄存器，故做写穿透：
//     写使能有效且写地址 == 读地址（且不是 r0）时，读口直接输出写数据
//   - 写数据来自 MEM/WB 流水寄存器，不依赖读口，不会形成组合环
// ============================================================================
module regfile (
    input  wire        clk,     // 时钟
    input  wire        we,      // 写使能
    input  wire [4:0]  ra1,     // 读地址 1（源操作数 A）
    input  wire [4:0]  ra2,     // 读地址 2（源操作数 B / 分支比较）
    input  wire [4:0]  wa,      // 写地址（目的寄存器）
    input  wire [31:0] wd,      // 写数据
    output wire [31:0] rd1,     // 读数据 1
    output wire [31:0] rd2      // 读数据 2
);

    reg [31:0] regs [0:31];
    integer i;
    // 上电清零（分布式 RAM 初始化）
    initial for (i = 0; i < 32; i = i + 1) regs[i] = 32'd0;

    // 异步读 + 同拍写穿透
    //   条件里排除 wa==0：r0 的写入被忽略，不能把 wd 旁路到 r0 读口。
    //   wd 来自 MEM/WB 流水寄存器，不在本模块的读路径上，故无组合环。
    assign rd1 = (we && (wa != 5'd0) && (wa == ra1)) ? wd : regs[ra1];
    assign rd2 = (we && (wa != 5'd0) && (wa == ra2)) ? wd : regs[ra2];

    // 同步写（r0 恒 0，不写入）
    always @(posedge clk) begin
        if (we && (wa != 5'd0))
            regs[wa] <= wd;
    end

endmodule
