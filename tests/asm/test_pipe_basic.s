/* ============================================================================
 * test_pipe_basic.s —— 流水线 Step 1「骨架直通」验证程序
 * ----------------------------------------------------------------------------
 * 目的：在不做转发 / 停顿 / 冲刷的前提下，验证五级流水的取指、译码、
 *       ALU 执行与 MMIO 写通路能按正确顺序推进。
 *
 * 观测方式（本版加强）：
 *   程序把每一条计算指令的结果都依次写到 LED 地址（0xD0000000），
 *   testbench（sim/tb_pipeline.v）按顺序逐笔比对整条 MMIO 写序列，
 *   而不是只看最后 4 笔 PASS。任何一条计算指令的数据通路出错，
 *   都会让对应那一笔写的值不匹配，测试立即 FAIL。
 *
 * 写序列顺序（共 30 笔，与 tb_pipeline.v 的 expected 表一一对应）：
 *   [ 0.. 6] 7 条常量初始化指令的结果（addi.w / lu12i.w / ori）
 *   [ 7..25] 19 条计算块指令的结果（含 pcaddu12i）
 *   [26..29] 结尾 4 笔 PASS 序列（与 test_all.s 一致）：
 *              LED       <- 0xFFFFFFFF
 *              seg_cs    <- 0xFFFFFFFF
 *              seg_data0 <- 0x7F
 *              seg_data1 <- 0x7F
 *
 * 约束（Step 1 明确范围）：
 *   - 只含算术 / 逻辑 / 移位类指令（含 lu12i.w、pcaddu12i、addi.w、andi/ori/xori）
 *   - 无分支、无跳转、无乘除
 *   - 除 MMIO 写外，不访问数据存储器
 *   - 所有计算结果写入互不相同的寄存器；计算块只读启动时常量，
 *     结果寄存器直到结尾才被读取。生产/消费距离 >= 5 条指令，
 *     远大于无转发流水线所需的 3 条，避免任何 RAW。
 *
 * pcaddu12i 的期望值推导：
 *   无分支 / 跳转时 PC 每拍 +4，第 i 条指令（从 _start 起 0 计）地址为
 *   0x1C000000 + 4*i。本程序中 pcaddu12i 是第 25 条（索引 25），
 *   地址 = 0x1C000000 + 0x64 = 0x1C000064。
 *   指令 `pcaddu12i $r28, 1`，si20 = 1：
 *       rd = PC + (si20 << 12) = 0x1C000064 + 0x1000 = 0x1C001064
 *   （实际地址由 `make -C tests/asm disasm` 反汇编核对，见文件末尾注释。）
 *
 * MMIO 映射（design/DESIGN.md §4.2）
 *   0xD0000000 W led[15:0]        0xD0000004 W seg_data0[7:0]
 *   0xD0000008 W seg_data1[7:0]   0xD000000C W seg_cs[7:0]
 *
 * 构建：make -C tests/asm test_pipe_basic
 * ============================================================================ */

    .text
    .globl _start
_start:

/* ---------------------------------------------------------------------------
 * 常量初始化（同时也是写序列 [0..6] 的数据源）
 *   全部用单条指令，源操作数为 $zero，避免伪指令展开造成相邻 RAW
 *   $r4  = 10              addi.w 正立即数
 *   $r5  = 3
 *   $r6  = 0xFFFFFFFF      addi.w 负立即数（si12 符号扩展）
 *   $r7  = 0x12345000      lu12i.w
 *   $r8  = 0x00000F0F      ori（ui12 零扩展）
 *   $r9  = 0x000000FF      ori
 *   $r10 = 0xD0000000      lu12i.w 的 20 位立即数带符号：-196608 = 0xD0000
 * -------------------------------------------------------------------------*/
    addi.w    $r4,  $zero, 10         /* [ 0] 0x1C000000 -> 0x0000000A */
    addi.w    $r5,  $zero, 3          /* [ 1] -> 0x00000003 */
    addi.w    $r6,  $zero, -1         /* [ 2] -> 0xFFFFFFFF */
    lu12i.w   $r7,  0x12345           /* [ 3] -> 0x12345000 */
    ori       $r8,  $zero, 0x0F0F     /* [ 4] -> 0x00000F0F */
    ori       $r9,  $zero, 0x00FF     /* [ 5] -> 0x000000FF */
    lu12i.w   $r10, -196608           /* [ 6] -> 0xD0000000（MMIO 基址） */

/* ---------------------------------------------------------------------------
 * 计算块（写序列 [7..25]，共 19 条）
 *   每条结果写入互不相同的寄存器，结果寄存器直到下面的 store 块才被读取，
 *   生产/消费距离 >= 25 条，无任何 RAW。
 *   用例刻意覆盖：负数、符号扩展、逻辑/算术右移差异、有/无符号比较、
 *   立即数零扩展（andi/ori/xori）与符号扩展（addi.w）。
 * -------------------------------------------------------------------------*/
    add.w     $r11, $r4, $r5          /* [ 7] 10 + 3            -> 0x0000000D */
    sub.w     $r12, $r5, $r4          /* [ 8] 3 - 10 = -7       -> 0xFFFFFFF9（负数） */
    addi.w    $r13, $r4, -7           /* [ 9] si12 符号扩展     -> 0x00000003 */
    and       $r14, $r8, $r9          /* [10] 0x0F0F & 0x00FF   -> 0x0000000F */
    or        $r15, $r8, $r9          /* [11] 0x0F0F | 0x00FF   -> 0x00000FFF */
    nor       $r16, $r8, $r9          /* [12] ~(0x0F0F | 0x00FF)-> 0xFFFFF000（负数） */
    xor       $r17, $r8, $r9          /* [13] 0x0F0F ^ 0x00FF   -> 0x00000FF0 */
    sll.w     $r18, $r4, $r5          /* [14] 10 << 3           -> 0x00000050 */
    srl.w     $r29, $r6, $r5          /* [15] 0xFFFFFFFF >> 3   -> 0x1FFFFFFF（逻辑右移） */
    sra.w     $r19, $r6, $r5          /* [16] 0xFFFFFFFF >>> 3  -> 0xFFFFFFFF（算术右移） */
    slt       $r20, $r5, $r4          /* [17] 有符号 3 < 10     -> 0x00000001 */
    sltu      $r21, $r6, $r5          /* [18] 无符号 0xFFFFFFFF < 3 -> 0x00000000 */
    andi      $r22, $r8, 0x0FF        /* [19] ui12 零扩展       -> 0x0000000F */
    xori      $r23, $r9, 0x0F         /* [20] 0x00FF ^ 0x000F   -> 0x000000F0 */
    slli.w    $r24, $r4, 4            /* [21] 10 << 4           -> 0x000000A0 */
    srli.w    $r25, $r6, 28           /* [22] 逻辑右移 28       -> 0x0000000F */
    ori       $r26, $zero, 0x7F       /* [23] ui12 零扩展       -> 0x0000007F */
    srai.w    $r30, $r6, 3            /* [24] 算术右移立即数 3  -> 0xFFFFFFFF */
    pcaddu12i $r28, 1                 /* [25] PC + 0x1000；PC=0x1C000064
                                       *      -> 0x1C001064 */

/* ---------------------------------------------------------------------------
 * 观测块：把上面每一条计算指令的结果依次写到 LED（写序列 [0..25]）
 *   每条 store 只读早就写好的结果寄存器，与生产点的距离 >= 25 条。
 * -------------------------------------------------------------------------*/
    st.w      $r4,  $r10, 0           /* [ 0] addi.w 常量 10 */
    st.w      $r5,  $r10, 0           /* [ 1] addi.w 常量 3 */
    st.w      $r6,  $r10, 0           /* [ 2] addi.w 常量 -1 */
    st.w      $r7,  $r10, 0           /* [ 3] lu12i.w 0x12345000 */
    st.w      $r8,  $r10, 0           /* [ 4] ori 0x00000F0F */
    st.w      $r9,  $r10, 0           /* [ 5] ori 0x000000FF */
    st.w      $r10, $r10, 0           /* [ 6] lu12i.w 0xD0000000 */

    st.w      $r11, $r10, 0           /* [ 7] add.w */
    st.w      $r12, $r10, 0           /* [ 8] sub.w */
    st.w      $r13, $r10, 0           /* [ 9] addi.w */
    st.w      $r14, $r10, 0           /* [10] and */
    st.w      $r15, $r10, 0           /* [11] or */
    st.w      $r16, $r10, 0           /* [12] nor */
    st.w      $r17, $r10, 0           /* [13] xor */
    st.w      $r18, $r10, 0           /* [14] sll.w */
    st.w      $r29, $r10, 0           /* [15] srl.w */
    st.w      $r19, $r10, 0           /* [16] sra.w */
    st.w      $r20, $r10, 0           /* [17] slt */
    st.w      $r21, $r10, 0           /* [18] sltu */
    st.w      $r22, $r10, 0           /* [19] andi */
    st.w      $r23, $r10, 0           /* [20] xori */
    st.w      $r24, $r10, 0           /* [21] slli.w */
    st.w      $r25, $r10, 0           /* [22] srli.w */
    st.w      $r26, $r10, 0           /* [23] ori */
    st.w      $r30, $r10, 0           /* [24] srai.w */
    st.w      $r28, $r10, 0           /* [25] pcaddu12i */

/* ---------------------------------------------------------------------------
 * PASS：写 MMIO（写序列 [26..29]）。与 test_all.s 的 PASS 序列完全一致。
 * 数据全部来自上面的 ALU 结果，因此该 PASS 同时验证了取指对齐、译码、
 * ALU 与 MMIO 写通路。
 * -------------------------------------------------------------------------*/
    st.w      $r30, $r10, 0           /* [26] LED       <- 0xFFFFFFFF */
    st.w      $r19, $r10, 12          /* [27] seg_cs    <- 0xFFFFFFFF */
    st.w      $r26, $r10, 4           /* [28] seg_data0 <- 0x7F */
    st.w      $r26, $r10, 8           /* [29] seg_data1 <- 0x7F */

/* ---------------------------------------------------------------------------
 * 末尾填充：addi.w $zero,$zero,0 不写寄存器、不访存、不产生 MMIO。
 * 防止 CPU 在 testbench 结束前取到未初始化的 IMEM 字（X）。
 * -------------------------------------------------------------------------*/
    .rept 256
    addi.w    $zero, $zero, 0
    .endr

/* 反汇编核对记录（make -C tests/asm disasm）：
 *   索引 25（地址 0x1C000064）应为：1c00003c  pcaddu12i $r28, 1
 *   若汇编器插入伪指令导致索引变化，必须同步修正上面的推导与 tb 期望值。
 */
