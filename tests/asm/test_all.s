/* ============================================================================
 * test_all.s —— LA32R 单周期 CPU 全指令上板自检程序
 * ----------------------------------------------------------------------------
 * 由 test_all.hex 反汇编还原（binutils 2.46.1），逐条对应原机器码。
 * 分支偏移改为符号标签，语义与原程序完全一致。
 *
 * 运行地址：程序被烧录到 IMEM 起始，实际执行的 PC 基址为 0x1C000000，
 *   故本程序在 0x1C000000 + 偏移 处运行（与 pc.v 复位值一致）。
 *   程序内部用 pcaddu12i 自测 PC 相对寻址，不依赖绝对重定位。
 *
 * 功能：遍历 8 个指令测试组，每组含若干测试项；每项算出实际结果与期望值
 *   比对，不等则跳转 FAIL。全部通过后写外设：LED 全亮、数码管显示 8 个 "8"，
 *   然后原地停机。
 *   失败时：LED = 组号<<8 | 项号；数码管第 0 位显示组号数字（0..5）。
 *
 * MMIO 映射（design/DESIGN.md §4.2）
 *   0xD0000000 W led[15:0]        0xD0000004 W seg_data0[7:0]
 *   0xD0000008 W seg_data1[7:0]   0xD000000C W seg_cs[7:0]
 *
 * 寄存器约定
 *   $t7 = 0xD0000000  MMIO 基址
 *   $t8 = 0x10000000  测试数据存储区基址
 *   $ra = 10, $tp = 3 测试源操作数
 *   $sp               结果暂存
 *   $s3               当前组号 0..7
 *   $s4               当前项号
 *   $s1               外设写入暂存
 *   $s2               期望值
 *   $a0 / $a1         被跳转指令顺带验证的目标寄存器
 *
 * 构建：见同目录 Makefile
 * ============================================================================ */

    .text
    .globl _start
_start:
/* ---------------------------------------------------------------------------
 * 初始化：MMIO 基址、测试数据区、源操作数
 * -------------------------------------------------------------------------*/
    li.w      $ra, 10               /* 源操作数 A */
    li.w      $tp, 3                /* 源操作数 B */
    lu12i.w   $t7, -196608          /* $t7 = 0xD0000000  MMIO 基址
                                       lu12i.w 的 20 位立即数是带符号的，
                                       0xD0000 写作 -196608（同一编码） */
    lu12i.w   $t8, 0x10000          /* $t8 = 0x10000000  测试数据存储区 */

/* ===========================================================================
 * 组 0：算术 add.w / sub.w / addi.w
 * =========================================================================*/
    li.w      $s3, 0
    add.w     $sp, $ra, $tp         /* 10 + 3 = 13 */
    li.w      $s4, 0
    li.w      $s2, 13
    bne       $s2, $sp, FAIL

    sub.w     $sp, $ra, $tp         /* 10 - 3 = 7 */
    li.w      $s4, 1
    li.w      $s2, 7
    bne       $s2, $sp, FAIL

    addi.w    $sp, $ra, 5           /* 10 + 5 = 15 */
    li.w      $s4, 2
    li.w      $s2, 15
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 1：大立即数 lu12i.w
 * =========================================================================*/
    lu12i.w   $sp, 0x12345          /* $sp = 0x12345000 */
    li.w      $s3, 1
    li.w      $s4, 3
    lu12i.w   $s2, 0x12345
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 2：比较 sltu / slt / slti / sltui，含 pcaddu12i 自测 PC 相对寻址
 * =========================================================================*/
    pcaddu12i $sp, 0                /* $sp = 当前 PC（应落在 0x1C000000 段内） */
    li.w      $s3, 2
    li.w      $s4, 4
    lu12i.w   $s2, 0x1C000          /* 0x1C000000 */
    sltu      $a0, $sp, $s2         /* 当前 PC < 0x1C000000 ? -> 应为 0 */
    li.w      $s2, 0
    bne       $s2, $a0, FAIL

    lu12i.w   $s2, 0x1C001          /* 0x1C001000 */
    sltu      $a0, $sp, $s2         /* 当前 PC < 0x1C001000 ? -> 应为 1 */
    li.w      $s2, 1
    bne       $s2, $a0, FAIL

    slt       $sp, $ra, $tp         /* 10 < 3 ? -> 0 */
    li.w      $s4, 5
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    sltu      $sp, $ra, $tp         /* 10 < 3 ? -> 0 */
    li.w      $s4, 6
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    slti      $sp, $ra, 15          /* 10 < 15 ? -> 1 */
    li.w      $s4, 7
    li.w      $s2, 1
    bne       $s2, $sp, FAIL

    sltui     $sp, $ra, 5           /* 10 < 5 ? -> 0 */
    li.w      $s4, 8
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 3：逻辑 and / or / nor / xor / andi / ori / xori
 * =========================================================================*/
    li.w      $s3, 3
    and       $sp, $ra, $tp         /* 10 & 3 = 2 */
    li.w      $s4, 0
    li.w      $s2, 2
    bne       $s2, $sp, FAIL

    or        $sp, $ra, $tp         /* 10 | 3 = 11 */
    li.w      $s4, 1
    li.w      $s2, 11
    bne       $s2, $sp, FAIL

    nor       $sp, $ra, $tp         /* ~(10 | 3) = -12 */
    li.w      $s4, 2
    li.w      $s2, -12
    bne       $s2, $sp, FAIL

    xor       $sp, $ra, $tp         /* 10 ^ 3 = 9 */
    li.w      $s4, 3
    li.w      $s2, 9
    bne       $s2, $sp, FAIL

    andi      $sp, $ra, 0x3         /* 10 & 3 = 2 */
    li.w      $s4, 4
    li.w      $s2, 2
    bne       $s2, $sp, FAIL

    ori       $sp, $ra, 0x100       /* 10 | 256 = 266 */
    li.w      $s4, 5
    li.w      $s2, 266
    bne       $s2, $sp, FAIL

    xori      $sp, $ra, 0xF         /* 10 ^ 15 = 5 */
    li.w      $s4, 6
    li.w      $s2, 5
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 4：移位 sll.w / srl.w / sra.w / slli.w / srai.w / rcri.w
 * =========================================================================*/
    li.w      $s3, 4
    sll.w     $sp, $ra, $tp         /* 10 << 3 = 80 */
    li.w      $s4, 0
    li.w      $s2, 80
    bne       $s2, $sp, FAIL

    srl.w     $sp, $ra, $tp         /* 10 >> 3 = 1 */
    li.w      $s4, 1
    li.w      $s2, 1
    bne       $s2, $sp, FAIL

    li.w      $a0, -1               /* $a0 = -10（0xFFFFFFF6） */
    addi.w    $a0, $a0, -9
    sra.w     $sp, $a0, $tp         /* 算术右移 3：-10 >> 3 = -2 */
    li.w      $s4, 2
    li.w      $s2, -1
    addi.w    $s2, $s2, -1          /* $s2 = -2 */
    bne       $s2, $sp, FAIL

    slli.w    $sp, $ra, 2           /* 10 << 2 = 40 */
    li.w      $s4, 3
    li.w      $s2, 40
    bne       $s2, $sp, FAIL

    srai.w    $sp, $ra, 1           /* 10 >> 1 = 5 */
    li.w      $s4, 4
    li.w      $s2, 5
    bne       $s2, $sp, FAIL

    li.w      $a0, -1               /* $a0 = -10（0xFFFFFFF6） */
    addi.w    $a0, $a0, -9
    rcri.w    $sp, $a0, 2           /* 循环右移 2：0xFFFFFFF6 -> 0xBFFFFFFD */
    li.w      $s4, 5
    li.w      $s2, -1
    addi.w    $s2, $s2, -2          /* $s2 = -3（0xFFFFFFFD） */
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 5：乘除 mul.w / mulh.w / mulh.wu / div.w / div.wu / mod.w / mod.wu
 *   MDU 为多周期单元，本组同时验证握手时序
 * =========================================================================*/
    li.w      $s3, 5
    mul.w     $sp, $ra, $tp         /* 低 32 位：10 * 3 = 30 */
    li.w      $s4, 0
    li.w      $s2, 30
    bne       $s2, $sp, FAIL

    mulh.w    $sp, $ra, $tp         /* 高 32 位：10 * 3 -> 0 */
    li.w      $s4, 1
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    mulh.wu   $sp, $ra, $tp         /* 无符号高 32 位 -> 0 */
    li.w      $s4, 2
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    div.w     $sp, $ra, $tp         /* 10 / 3 = 3 */
    li.w      $s4, 3
    li.w      $s2, 3
    bne       $s2, $sp, FAIL

    div.wu    $sp, $ra, $tp         /* 无符号 10 / 3 = 3 */
    li.w      $s4, 4
    li.w      $s2, 3
    bne       $s2, $sp, FAIL

    mod.w     $sp, $ra, $tp         /* 10 % 3 = 1 */
    li.w      $s4, 5
    li.w      $s2, 1
    bne       $s2, $sp, FAIL

    mod.wu    $sp, $ra, $tp         /* 无符号 10 % 3 = 1 */
    li.w      $s4, 6
    li.w      $s2, 1
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 6：访存 st.w/ld.w/st.h/ld.h/ld.hu/st.b/ld.b/ld.bu（验证符号扩展）
 * =========================================================================*/
    li.w      $s3, 6
    lu12i.w   $s2, 0x12345
    ori       $s2, $s2, 0x678       /* $s2 = 0x12345678 */
    st.w      $s2, $t8, 0
    ld.w      $sp, $t8, 0
    li.w      $s4, 1
    bne       $s2, $sp, FAIL

    lu12i.w   $s2, 0x5              /* $s2 = 0x00050678 */
    ori       $s2, $s2, 0x678
    st.h      $s2, $t8, 4           /* 存半字 0x0678 */
    ld.h      $sp, $t8, 4           /* 读回并符号扩展 -> 0x00000678 */
    li.w      $s4, 3
    bne       $s2, $sp, FAIL

    ld.hu     $sp, $t8, 4           /* 读回零扩展 -> 0x00000678 */
    li.w      $s4, 4
    bne       $s2, $sp, FAIL

    li.w      $s2, -1
    st.b      $s2, $t8, 8           /* 存字节 0xFF */
    ld.b      $sp, $t8, 8           /* 符号扩展 -> 0xFFFFFFFF */
    li.w      $s4, 6
    li.w      $s2, -1
    bne       $s2, $sp, FAIL

    ld.bu     $sp, $t8, 8           /* 零扩展 -> 0x000000FF */
    li.w      $s4, 7
    li.w      $s2, 255
    bne       $s2, $sp, FAIL

/* ===========================================================================
 * 组 7：分支与跳转 beq / bne / blt / bge / bltu / bgeu / b / bl / jirl
 *   判据：条件成立则应跳过紧邻的 li.w $sp, 1，使 $sp 保持 0
 * =========================================================================*/
    li.w      $s3, 7

    li.w      $sp, 0
    beq       $ra, $ra, 1f          /* $ra == $ra 恒真 -> 跳过下一条 */
    li.w      $sp, 1
1:
    li.w      $s4, 0
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    li.w      $sp, 0
    bne       $ra, $tp, 2f          /* 10 != 3 为真 -> 跳过下一条 */
    li.w      $sp, 1
2:
    li.w      $s4, 1
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    li.w      $sp, 0
    blt       $tp, $ra, 3f          /* 3 < 10 为真 -> 跳过下一条 */
    li.w      $sp, 1
3:
    li.w      $s4, 2
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    li.w      $sp, 0
    bge       $ra, $tp, 4f          /* 10 >= 3 为真 -> 跳过下一条 */
    li.w      $sp, 1
4:
    li.w      $s4, 3
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    li.w      $sp, 0
    bltu      $tp, $ra, 5f          /* 3 < 10 无符号为真 -> 跳过下一条 */
    li.w      $sp, 1
5:
    li.w      $s4, 4
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    li.w      $sp, 0
    bgeu      $ra, $tp, 6f          /* 10 >= 3 无符号为真 -> 跳过下一条 */
    li.w      $sp, 1
6:
    li.w      $s4, 5
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    /* b：无条件跳过置位语句 */
    li.w      $sp, 0
    b         7f
    li.w      $sp, 1
7:
    li.w      $s4, 6
    li.w      $s2, 0
    bne       $s2, $sp, FAIL

    /* bl / jirl 配合：bl 跳到标签 9 并把返回地址写入 $ra；
       9 处设 $sp=1 后用 jirl 借 $ra 跳回标签 8，验证链接寄存器与间接跳转。
       注意证据值 $sp=1 是设在 bl 的「跳转目标」里，而非返回路径上 */
    li.w      $sp, 0
    bl        9f                    /* 跳到 9f，$ra <- 标签 8 的地址 */
8:
    li.w      $a0, 0                /* jirl 跳回此处执行，作为"确实跳回来了"的证据 */
    b         10f                   /* 跳过 9 段，避免顺序执行又落进 jirl */
9:
    li.w      $sp, 1                /* 在 bl 的跳转目标处设置证据值 */
    jirl      $a1, $ra, 0           /* 跳回 $ra（标签 8），同时把 PC+4 写入 $a1 */
10:
    li.w      $s4, 7
    li.w      $s2, 1
    bne       $s2, $sp, FAIL        /* 校验 $sp == 1，证明 bl 与 jirl 往返成功 */

/* ===========================================================================
 * 全部通过：LED 全亮 + 数码管 88888888，然后原地停机
 * =========================================================================*/
PASS:
    li.w      $s1, -1
    st.w      $s1, $t7, 0           /* LED       <- 0xFFFFFFFF 全亮 */
    li.w      $s1, -1
    st.w      $s1, $t7, 12          /* seg_cs    <- 0xFFFFFFFF 全位选 */
    li.w      $s1, 127
    st.w      $s1, $t7, 4           /* seg_data0 <- 0x7F 显示 "8" */
    li.w      $s1, 127
    st.w      $s1, $t7, 8           /* seg_data1 <- 0x7F 显示 "8" */
HALT:
    b         HALT                  /* 原地停机 */

/* ===========================================================================
 * 失败：LED 显示「组号<<8 | 项号」，数码管第 0 位显示组号数字
 *   段码为共阴极高有效编码：0->0x3F, 1->0x06, 2->0x5B, 3->0x4F, 4->0x66, 5->0x6D
 * =========================================================================*/
FAIL:
    slli.w    $s1, $s3, 8
    or        $s1, $s1, $s4
    st.w      $s1, $t7, 0           /* LED <- 错误码 */
    li.w      $s1, 1
    st.w      $s1, $t7, 12          /* seg_cs <- 1，仅点亮最低位 */
    li.w      $s1, 0x3F             /* 数字 0 */
    bne       $s3, $zero, F_GRP1
    b         FAIL_STORE
F_GRP1:
    li.w      $s1, 0x06             /* 数字 1 */
    addi.w    $s3, $s3, -1
    bne       $s3, $zero, F_GRP2
    b         FAIL_STORE
F_GRP2:
    li.w      $s1, 0x5B             /* 数字 2 */
    addi.w    $s3, $s3, -1
    bne       $s3, $zero, F_GRP3
    b         FAIL_STORE
F_GRP3:
    li.w      $s1, 0x4F             /* 数字 3 */
    addi.w    $s3, $s3, -1
    bne       $s3, $zero, F_GRP4
    b         FAIL_STORE
F_GRP4:
    li.w      $s1, 0x66             /* 数字 4 */
    addi.w    $s3, $s3, -1
    bne       $s3, $zero, F_GRP5
    b         FAIL_STORE
F_GRP5:
    li.w      $s1, 0x6D             /* 数字 5（组号 >=5 一律显示 5） */
FAIL_STORE:
    st.w      $s1, $t7, 4           /* seg_data0 <- 组号数字 */
    b         FAIL_STORE            /* 原地停机，等待复位 */
